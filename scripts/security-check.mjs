#!/usr/bin/env node
/**
 * Refuse to build or start on a tree that carries the loader which has been
 * force-pushed into this repository since August 2026.
 *
 * It runs before `npm run dev` / `npm run build` (the "pre" hooks), in the
 * Docker builder stage, and from next.config.mjs — so it also runs when Next
 * is started directly (`npx next dev`, an IDE task, the E2E stack), which the
 * npm hooks do not cover.
 *
 * The loader changes its strings from version to version, so the rules below
 * describe how it hides and how it gets started rather than what it says:
 *
 *   hiding   – code after a long run of blanks on a line; one very long line
 *              in a source file; a file with code but without an extension;
 *   starting – `node <file>` chained into package.json scripts, install
 *              hooks, an editor task that runs when the folder is opened;
 *   known    – names, addresses and code shapes seen in past versions.
 *
 * Usage: node scripts/security-check.mjs [--root <dir>]
 * Exit code 1 and a list of findings when something is found.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs"
import { basename, join, relative, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const HERE = fileURLToPath(import.meta.url)
const REPO_ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..")

/** Joined from parts so that this file does not match its own list. */
const re = (parts, flags) => new RegExp(parts.join(""), flags)

// Strings and code shapes of the versions seen so far.
const KNOWN = [
  // Ethereum addresses the loader reads its server address from.
  re(["0xa322E5f3", "D311D3080e6f0121063e9aDC2490Ef1a"], "i"),
  re(["0x1eEf0849", "EDa15d87f64e51C73C8442Cf3c8bCEF3"], "i"),
  // A web shop has no business talking to an Ethereum node.
  re(["eth_", "(blockNumber|getBlockByNumber|getTransactionCount|getTransactionByHash)"]),
  re(["eth\\.blockscout", "\\.com"]),
  re(["1rpc\\.io", "\\/eth"]),
  // How the second stage is fetched and started.
  re(["X-Payload-", "B64"], "i"),
  re(["\\/0x\\/", "c?ls\\b"]),
  re(["['\"]node['\"]\\s*,\\s*\\[\\s*['\"]", "-[ei]['\"]"]),
  re(["global\\.i", "\\s*="]),
  re(["global\\[['\"]_", "(t_u|t_s|H2?|V)['\"]\\]"]),
  re(["_lint", "Placeholder"]),
  // The unpacking routine of the packed string table (base91 with its own alphabet).
  re(["&\\s*8191\\s*\\)\\s*>\\s*88\\s*\\?", "\\s*13\\s*:\\s*14"]),
  // Older versions.
  re(["BLOCK_", "MULTIPLE"]),
  re(["run_", "loader"]),
  re(["_0x05a", "598"]),
  re(["atob\\(_0x"]),
]

// Running text as code has no use in this project; scripts that start
// processes live only in the folders listed in MAY_START_PROCESSES.
const RUNS_TEXT_AS_CODE = re(["\\bev", "al\\s*\\(|new\\s+Func", "tion\\s*\\("])
const STARTS_PROCESSES = re(["child_", "process"])
const MAY_START_PROCESSES = ["scripts/", "e2e/stack/"]

const CODE_EXT = new Set([".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx"])
const DATA_EXT = new Set([".json"])
// What an editor keeps in its folder: settings, snippets, spelling word lists.
const EDITOR_DATA_EXT = new Set([".json", ".jsonc", ".code-snippets", ".dict", ".txt", ".md"])
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  ".git",
  "dist",
  "out",
  "coverage",
  ".vercel",
  ".turbo",
  // Generated by test runs; full of bundled, minified viewer code.
  "playwright-report",
  "test-results",
  "blob-report",
])

// Files without an extension that belong in a repository.
const PLAIN_NAMES = new Set(["Dockerfile", "Makefile", "LICENSE", "README", "CODEOWNERS", "Procfile", "NOTICE"])

// Files the loader's own push automation leaves behind, and past droppers.
const DROPPER_NAMES = new Set(["api.js", "init", "temp_auto_push.bat", "temp_interactive_push.bat", "branch_structure.json"])

const MAX_LINE = 3000
const MAX_BLANK_RUN = 200
const MAX_FILE_BYTES = 2 * 1024 * 1024
const HIDDEN_AFTER_BLANKS = new RegExp(`\\S[ \\t]{${MAX_BLANK_RUN},}\\S`)

// The only programs package.json scripts may start with `node`.
const NODE_TARGET_OK = /^scripts\/[\w.-]+\.mjs$/
const INSTALL_HOOKS = ["preinstall", "install", "postinstall", "prepare", "prepublish", "prepack", "postpack"]

const LOOKS_LIKE_CODE = /\brequire\s*\(|\bfunction\b|=>|\bimport\s|\bconst\s|\bvar\s/

function walk(dir, out = []) {
  let names
  try {
    names = readdirSync(dir)
  } catch {
    return out
  }
  for (const name of names) {
    if (SKIP_DIRS.has(name)) continue
    const path = join(dir, name)
    let st
    try {
      st = statSync(path)
    } catch {
      continue
    }
    if (st.isDirectory()) walk(path, out)
    else out.push({ path, size: st.size })
  }
  return out
}

const extOf = (name) => {
  const dot = name.lastIndexOf(".")
  // ".gitignore" is a name, not an extension.
  return dot > 0 ? name.slice(dot) : ""
}

function checkPackageJson(root, errors) {
  const path = join(root, "package.json")
  if (!existsSync(path)) return
  let pkg
  try {
    pkg = JSON.parse(readFileSync(path, "utf8"))
  } catch {
    errors.push("package.json is not valid JSON")
    return
  }
  const scripts = pkg.scripts || {}
  for (const [name, cmd] of Object.entries(scripts)) {
    if (typeof cmd !== "string") continue
    if (INSTALL_HOOKS.includes(name)) {
      errors.push(`package.json has an install hook "${name}" (${cmd}): it runs on every install`)
    }
    // Every `node <file>` in a script: the file must be one of ours.
    for (const match of cmd.matchAll(/(?:^|[\s;&|(])node(?:\.exe)?\s+((?:-[^\s]+\s+)*)([^\s;&|)]+)/g)) {
      const target = match[2].replace(/^\.\//, "").replace(/\\/g, "/")
      if (!NODE_TARGET_OK.test(target)) {
        errors.push(`package.json script "${name}" starts an unexpected program: node ${target} (${cmd})`)
      }
    }
  }
}

function checkEditorFolder(rel, text, errors) {
  const ext = extOf(basename(rel))
  if (!EDITOR_DATA_EXT.has(ext)) {
    errors.push(`Unexpected file in the editor folder: ${rel} (only settings and word lists belong there)`)
    return
  }
  if (/"runOn"\s*:\s*"folderOpen"/.test(text)) {
    errors.push(`Editor task that runs when the folder is opened: ${rel}`)
  }
  if (/"task\.allowAutomaticTasks"\s*:\s*(true|"on")/.test(text)) {
    errors.push(`Editor setting that lets tasks run without asking: ${rel}`)
  }
}

/**
 * Look through a source tree and return what was found, one line per finding.
 * An empty list means the tree is clean by every rule above.
 */
export function scanTree(root = REPO_ROOT) {
  const errors = []
  root = resolve(root)

  checkPackageJson(root, errors)

  const ignore = join(root, ".gitignore")
  if (existsSync(ignore)) {
    const lines = readFileSync(ignore, "utf8").split(/\r?\n/).map((line) => line.trim())
    if (lines.includes(".gitignore") || lines.includes("/.gitignore")) {
      errors.push(".gitignore hides itself: changes to the ignore list would go unnoticed")
    }
    for (const name of DROPPER_NAMES) {
      if (lines.includes(name) || lines.includes(`/${name}`)) {
        errors.push(`.gitignore hides a file the loader uses: ${name}`)
      }
    }
  }

  for (const { path, size } of walk(root)) {
    if (path === HERE) continue
    const rel = relative(root, path).replace(/\\/g, "/")
    const name = basename(path)
    const ext = extOf(name)
    const atRoot = !rel.includes("/")
    const inEditorFolder = rel.startsWith(".vscode/") || rel.startsWith(".cursor/")
    const isCode = CODE_EXT.has(ext)
    const noExt = ext === "" && !name.startsWith(".") && !PLAIN_NAMES.has(name)

    if (atRoot && DROPPER_NAMES.has(name)) {
      errors.push(`Known dropper file present: ${rel}`)
    }
    if (!isCode && !DATA_EXT.has(ext) && !noExt && !inEditorFolder) continue
    if (size > MAX_FILE_BYTES) continue

    let text
    try {
      text = readFileSync(path, "utf8")
    } catch {
      continue
    }
    // Not text: an image or a font without an extension.
    if (text.includes("\u0000")) continue

    if (inEditorFolder) checkEditorFolder(rel, text, errors)

    for (const pattern of KNOWN) {
      if (pattern.test(text)) errors.push(`Known loader pattern ${pattern} in ${rel}`)
    }

    if (noExt && LOOKS_LIKE_CODE.test(text)) {
      errors.push(`Code in a file without an extension: ${rel}`)
    }

    if (isCode || noExt || inEditorFolder) {
      if (RUNS_TEXT_AS_CODE.test(text)) {
        errors.push(`Runs text as code in ${rel}`)
      }
      if (STARTS_PROCESSES.test(text) && !MAY_START_PROCESSES.some((dir) => rel.startsWith(dir))) {
        errors.push(`Starts other programs outside ${MAY_START_PROCESSES.join(", ")}: ${rel}`)
      }
      // Static assets may be minified; everything else is written by hand.
      const lengthMatters = !rel.startsWith("public/")
      const lines = text.split(/\r?\n/)
      for (let i = 0; i < lines.length; i++) {
        const line = lines[i]
        if (lengthMatters && line.length > MAX_LINE) {
          errors.push(`Very long line (${line.length} characters) in ${rel}:${i + 1}`)
        }
        if (line.length > MAX_BLANK_RUN && HIDDEN_AFTER_BLANKS.test(line)) {
          errors.push(`Code hidden after a long run of blanks in ${rel}:${i + 1}`)
        }
      }
    }
  }

  return [...new Set(errors)]
}

/** Stop the process with the list of findings if the tree is not clean. */
export function assertCleanTree(root = REPO_ROOT) {
  const errors = scanTree(root)
  if (!errors.length) return
  console.error("security-check FAILED: this tree carries signs of the injected loader.")
  for (const error of errors) console.error(`  - ${error}`)
  console.error("Do not run, build or open it in an editor. Compare the branch with a known clean commit.")
  process.exit(1)
}

const runDirectly = process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url
if (runDirectly) {
  const flag = process.argv.indexOf("--root")
  assertCleanTree(flag > -1 ? process.argv[flag + 1] : REPO_ROOT)
  console.log("security-check OK")
}
